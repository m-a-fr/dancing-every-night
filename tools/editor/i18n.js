/* Langue de l'éditeur : français (texte source, écrit tel quel dans index.html et le code) ou anglais.
   Une chaîne française sert de clé : tr("Enregistré") rend "Saved" en anglais, la chaîne elle-même en français.
   Variables : tr("Chanson « {title} » créée", { title }). Le HTML statique est traduit au chargement par
   i18nApply() : textes et attributs (title, placeholder, aria-label, alt) cherchés tels quels, et blocs marqués
   data-i18n traduits d'un seul tenant (innerHTML, espaces normalisés). Langue : choix gardé dans ce navigateur,
   sinon celle du navigateur (français si elle commence par « fr », anglais sinon). */
const I18N_KEY = "dne-editor-lang";
const LANG = (() => {
  try { const v = localStorage.getItem(I18N_KEY); if (v === "fr" || v === "en") return v; } catch (_) {}
  return /^fr\b/i.test(navigator.language || "") ? "fr" : "en";
})();
const i18nMissing = new Set();   // chaînes sans traduction rencontrées (contrôle : i18nMissing dans la console)

function tr(fr, vars) {
  let s = fr;
  if (LANG === "en") {
    const k = fr.replace(/\s+/g, " ").trim();
    if (Object.prototype.hasOwnProperty.call(EN, k)) s = EN[k];
    else if (k && /[a-zà-ÿ]/i.test(k)) i18nMissing.add(k);
  }
  return vars ? s.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : s;
}
// Pluriel simple : trn(n, "{n} note", "{n} notes")
function trn(n, one, many, vars) { return tr(n === 1 ? one : many, { n, ...vars }); }

function setLang(lang) {
  try { localStorage.setItem(I18N_KEY, lang); } catch (_) {}
  location.reload();
}

const I18N_ATTRS = ["title", "placeholder", "aria-label", "alt"];
function i18nApply(root = document.body) {
  document.documentElement.lang = LANG;
  if (LANG !== "en") return;
  for (const el of root.querySelectorAll("[data-i18n]")) el.innerHTML = tr(el.innerHTML);
  for (const el of [root, ...root.querySelectorAll("*")]) {
    for (const a of I18N_ATTRS) if (el.hasAttribute(a)) el.setAttribute(a, tr(el.getAttribute(a)));
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: n => (n.parentElement.closest("[data-i18n], script, style, code") ? NodeFilter.FILTER_REJECT
                      : n.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT),
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const n of nodes) {
    const v = n.nodeValue, lead = v.match(/^\s*/)[0], trail = v.match(/\s*$/)[0];
    n.nodeValue = lead + tr(v.trim()) + trail;
  }
}

